"""Pack the tokenizers for the demo page into tokenizers.js (loaded with a
plain <script>, so the page also works when opened straight from disk).

    .venv/Scripts/python engine/demo/build_tokenizers.py

All are GPT-2-style byte-level BPE (add_prefix_space false, <|endoftext|> = 0);
the page selects one by the vocabulary size the board reports.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
SRC = {
    4096: ("mcu-lm combo (ours, 2M params, TinyStories)", ROOT / "data" / "tok4096.json"),
    8192: ("mcu-lm varC (ours, 8.6M params, TinyStories)", ROOT / "data" / "tok8192.json"),
    32768: ("esp32-ai TinyStories (slvDev, 29M params, MIT)", ROOT / "engine" / "out" / "esp32ai" / "tokenizer.json"),
}


def main():
    out = {}
    for vocab, (label, path) in SRC.items():
        j = json.loads(path.read_text(encoding="utf-8"))
        v = j["model"]["vocab"]
        ids = [None] * (max(v.values()) + 1)
        for t, i in v.items():
            ids[i] = t
        merges = [m if isinstance(m, str) else " ".join(m) for m in j["model"]["merges"]]
        out[vocab] = dict(label=label, tokens=ids, merges=merges, eot=0)
    js = "// Generated by build_tokenizers.py. Byte-level BPE vocabularies for the demo page.\n"
    js += "window.TOKENIZERS = " + json.dumps(out, ensure_ascii=False, separators=(",", ":")) + ";\n"
    dst = Path(__file__).with_name("tokenizers.js")
    dst.write_text(js, encoding="utf-8")
    print(f"wrote {dst} ({dst.stat().st_size / 1e6:.2f} MB)")


if __name__ == "__main__":
    main()
